/*
 * Имитатор очага пламени.
 *
 * Очаг горит постоянно и гаснет только кнопкой на себе — тем, кто его
 * нашёл. О тушении плата сообщает центру, и по этому сигналу
 * засчитывается задание маршрута.
 *
 * Сам он больше не загорается: зажигание — это подготовка зала, а её
 * ведёт человек. Иначе очаг вспыхивал бы за спиной у звена, которое
 * его уже потушило, и задание засчитывалось бы дважды.
 *
 * Нагрузкой (лампой, дымовой шашкой, чем угодно) управляет реле на
 * отдельной ноге.
 */
#ifndef FIRE_H
#define FIRE_H

#include <stdbool.h>
#include <stdint.h>

/*
 * Реле очага. Управление прямое: единица на ноге включает нагрузку.
 *
 * D10 на разъёме Arduino: свободен и не пересекается ни с линиями
 * Ethernet, ни с USART, ни с кнопкой.
 */
#ifndef FIRE_RELAY_PORT
#define FIRE_RELAY_PORT GPIOD
#endif
#ifndef FIRE_RELAY_PIN
#define FIRE_RELAY_PIN GPIO14 /* D10 */
#endif

/*
 * Кнопка тушения на самом очаге. Вход с подтяжкой вверх, нажатие
 * сажает ногу на землю: лишних деталей не нужно, а оборванный провод
 * читается как «не нажато» — очаг останется гореть, и это заметят.
 */
#ifndef FIRE_BUTTON_PORT
#define FIRE_BUTTON_PORT GPIOF
#endif
#ifndef FIRE_BUTTON_PIN
#define FIRE_BUTTON_PIN GPIO12 /* D8 */
#endif

/* Время подтверждения контакта кнопки, мс. */
#define FIRE_DEBOUNCE_MS 30U

/*
 * Настроить реле и кнопку.
 *
 * Очаг при старте зажигается: плату включают перед занятием, и зал
 * должен быть готов без лишних действий. Потушенный после нажатия, он
 * сам не возвращается — зажигает его команда центра или перезапуск.
 */
void fire_init(void);

/*
 * Обслуживание очага. Вызывать из главного цикла.
 *
 * Возвращает true, если состояние изменилось — загорелся сам или
 * потушен кнопкой. Тогда об этом сообщают центру.
 */
bool fire_poll(void);

/* Горит ли очаг сейчас. */
bool fire_is_burning(void);

/* Чем вызвано последнее изменение: "button" — потушен кнопкой,
 * "command" — зажжён или потушен центром, "init" — состояние при
 * включении платы. */
const char *fire_last_reason(void);

/* Зажечь или потушить по команде центра. */
void fire_set(bool burning);

#endif /* FIRE_H */
