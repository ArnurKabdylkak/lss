/*
 * Ударный молот: счёт повторений герконом.
 *
 * Магнит на подвижной части проходит мимо геркона дважды за полный
 * цикл — на замахе и на возврате. Поэтому повторением считается не
 * каждое срабатывание, а каждое второе: иначе зачёт оказался бы вдвое
 * щедрее, чем работа.
 *
 * Счёт ведёт плата, а не центр. Центр видит только итог, и по нему
 * сверяет заданное оператором с тем, что сделано (сценарий
 * теплокамеры §5).
 */
#ifndef LOAD_H
#define LOAD_H

#include <stdbool.h>
#include <stdint.h>

/*
 * Геркон. Вход с подтяжкой вверх: замкнутый магнитом контакт сажает
 * ногу на землю. Оборванный провод при такой схеме читается как
 * «нет срабатываний» — счёт замирает, и это заметят, а не зачтут
 * лишнего.
 */
#ifndef LOAD_REED_PORT
#define LOAD_REED_PORT GPIOF
#endif
#ifndef LOAD_REED_PIN
#define LOAD_REED_PIN GPIO12 /* D8 */
#endif

/*
 * Сколько проходов геркона составляют одно повторение.
 *
 * Два: магнит идёт мимо него туда и обратно. Вынесено в настройку —
 * на другой механике движение может быть одно.
 */
#ifndef LOAD_PASSES_PER_REP
#define LOAD_PASSES_PER_REP 2U
#endif

/*
 * Время подтверждения контакта, мс.
 *
 * Геркон звенит при замыкании и размыкании, а удар по механизму
 * отдаётся дрожанием. Без выдержки один взмах насчитал бы несколько
 * повторений.
 */
#ifndef LOAD_DEBOUNCE_MS
#define LOAD_DEBOUNCE_MS 25U
#endif

/*
 * Наименьший промежуток между повторениями, мс.
 *
 * Быстрее человек не работает: всё, что чаще, — дребезг механики или
 * наводка на длинном проводе.
 */
#ifndef LOAD_MIN_REP_MS
#define LOAD_MIN_REP_MS 250U
#endif

/* Вес груза на установке, килограммы. Передаётся в каждом отчёте:
 * его меняют между подходами, и по одному событию смены его не
 * восстановить, если пакет потерялся. */
#ifndef LOAD_WEIGHT_KG
#define LOAD_WEIGHT_KG 25U
#endif

/* Настроить вход геркона. */
void load_init(void);

/*
 * Обслуживание счётчика. Вызывать из главного цикла.
 *
 * Возвращает true, когда засчитано очередное повторение: о нём
 * сообщают центру отдельным событием.
 */
bool load_poll(void);

/* Сколько повторений засчитано с момента включения платы.
 *
 * Счётчик накопительный и между заходами не обнуляется: результат
 * захода центр считает приростом, и сброс на плате лишил бы его
 * возможности отличить новый заход от перезапуска. */
uint16_t load_reps(void);

/* Сколько проходов геркона было всего: нужно наладке, чтобы отличить
 * «механика не доходит до геркона» от «геркон не срабатывает». */
uint32_t load_passes(void);

#endif /* LOAD_H */
