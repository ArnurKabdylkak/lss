/*
 * Поиск разводки клавиатуры: какая пара ног замыкается нажатием.
 *
 * Нужен при монтаже. У матричной клавиатуры порядок строк и столбцов
 * у каждой модели свой, и выяснять его по описаниям бесполезно —
 * плата определяет его сама.
 */
#ifndef DISCOVER_H
#define DISCOVER_H

#include <stdbool.h>

/* Настроить ноги разъёма для поиска. */
void discover_init(void);

/*
 * Один проход по всем ногам. О каждой найденной паре сообщается
 * через report; stuck — пара была замкнута с первых секунд работы,
 * то есть это не нажатие, а залипший контакт или провод на земле.
 */
void discover_scan(void (*report)(const char *a, const char *b, bool stuck));

#endif /* DISCOVER_H */
