/*
 * Роль платы: чем она работает на объекте.
 *
 * Прошивка одна, а плат на объекте несколько и заняты они разным:
 * стойка набора чисел, имитатор очага. Общее — тактирование, сеть,
 * консоль и командный тракт; различается главный цикл.
 *
 * Роль выбирается сборкой (build_src_filter в platformio.ini), а не
 * флагом в коде: так в прошивку не попадает чужой цикл, и ошибиться
 * ролью в рабочем режиме невозможно.
 */
#ifndef ROLE_H
#define ROLE_H

#include <stdint.h>

/* Главный цикл роли. Вызывается из main() после общей настройки и не
 * возвращает управление. */
void role_run(void);

/* Печать в консоль платы. Своя у каждой роли быть не должна: консоль
 * одна, и формат вывода общий. */
void role_puts(const char *s);

/* Печать числа: printf с плавающей точкой на плату не тянем. */
void role_put_u32(uint32_t value);

#endif /* ROLE_H */
