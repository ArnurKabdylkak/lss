/*
 * Матричная клавиатура 4x4 для STM32F767 (аналог Arduino-библиотеки Keypad).
 *
 * Строки — выходы, столбцы — входы с подтяжкой вверх. Сканирование
 * неблокирующее: keypad_poll() вызывается из главного цикла, нажатия
 * складываются в очередь, keypad_get_key() их забирает.
 *
 * Разводка повторяет исходную схему на Arduino (строки D6..D9,
 * столбцы D5..D2) в терминах Arduino-пинов Nucleo-F767ZI.
 *
 * Раскладка зависит от того, какая клавиатура стоит на стойке, и
 * задаётся из platformio.ini. Ошибиться здесь легко и неприятно: на
 * шестнадцатеричной матрице нет клавиш «решётка» и «звёздочка», и
 * набранный код нечем подтвердить — человек жмёт кнопки, а стойка
 * молчит.
 */
#ifndef KEYPAD_H
#define KEYPAD_H

#include <stdbool.h>
#include <stdint.h>

#define KEYPAD_ROWS 4
#define KEYPAD_COLS 4

/*
 * Раскладка матрицы.
 *
 * 0 — обычная плёночная клавиатура: цифры, «звёздочка», «решётка» и
 * столбец A–D справа. 1 — шестнадцатеричная: 0–9 и A–F.
 */
#ifndef KEYPAD_LAYOUT_HEX
#define KEYPAD_LAYOUT_HEX 0
#endif

/* Символ, возвращаемый когда нажатий нет. */
#define KEYPAD_NO_KEY '\0'

/* Интервал сканирования матрицы, мс. */
#define KEYPAD_SCAN_INTERVAL_MS 5U

/* Время подтверждения состояния контакта, мс. */
#define KEYPAD_DEBOUNCE_MS 20U

/* Настроить GPIO клавиатуры. Вызывать после настройки тактирования. */
void keypad_init(void);

/* Просканировать матрицу, если подошло время. Вызывать из главного цикла. */
void keypad_poll(void);

/* Забрать следующее нажатие из очереди. KEYPAD_NO_KEY, если очередь пуста. */
char keypad_get_key(void);

/* Нажата ли сейчас хотя бы одна клавиша. */
bool keypad_is_pressed(void);

#endif /* KEYPAD_H */
