/*
 * Проверка кода, набираемого на клавиатуре стойки.
 *
 * Плата отвечает ровно на один вопрос: набранный код верен или нет.
 * Ничего не разблокирует и ничем не управляет — результат уходит
 * в телеметрию и на индикацию, и на этом роль кода заканчивается.
 *
 * Набор: цифры накапливаются, одна клавиша проверяет набранное,
 * другая стирает. Какие именно — зависит от клавиатуры на стойке,
 * поэтому они вынесены в настройку: на шестнадцатеричной матрице
 * «решётки» и «звёздочки» нет вовсе.
 */
#ifndef CODE_H
#define CODE_H

#include <stdbool.h>
#include <stdint.h>

/* Клавиши подтверждения и стирания. Умолчание — плёночная матрица. */
#ifndef CODE_KEY_ENTER
#define CODE_KEY_ENTER '#'
#endif
#ifndef CODE_KEY_CLEAR
#define CODE_KEY_CLEAR '*'
#endif

/* Предельная длина кода. Больше на матричной клавиатуре не набирают,
 * а буфер должен быть фиксированным: динамической памяти на плате нет. */
#define CODE_MAX_LEN 12

/* Код по умолчанию — до того, как его сменили командой. */
#define CODE_DEFAULT "1234"

/*
 * Пауза, после которой недобранный код стирается сам.
 *
 * Иначе цифры, набранные час назад кем-то другим, дописались бы к
 * новому вводу, и человек не понял бы, почему код «неверный».
 */
#define CODE_ENTRY_TIMEOUT_MS 15000U

/*
 * Сколько неудач подряд допускается, прежде чем ввод придерживается
 * паузой. Четырёхзначный код иначе подбирается за считаные минуты.
 */
#define CODE_MAX_ATTEMPTS 3
#define CODE_LOCKOUT_MS 30000U

enum code_result {
    CODE_PENDING = 0, /* ввод продолжается, ответа ещё нет */
    CODE_VALID,       /* код верен */
    CODE_INVALID,     /* код неверен */
    CODE_LOCKED,      /* слишком много неудач подряд, идёт пауза */
    CODE_CLEARED,     /* набранное стёрто */
};

/* Настроить проверку и задать код по умолчанию. */
void code_init(void);

/*
 * Принять нажатие клавиши.
 *
 * Возвращает CODE_PENDING, пока идёт набор; иное значение — ответ на
 * подтверждение ввода.
 */
enum code_result code_feed(char key);

/* Сменить код. false — код короче трёх символов, длиннее CODE_MAX_LEN
 * или содержит не цифры. */
bool code_set(const char *code);

/* Сколько символов набрано сейчас: для индикации, без раскрытия самих
 * символов. */
uint8_t code_entered(void);

/* Идёт ли пауза после неудачных попыток. */
bool code_is_locked(void);

/* Текстовое имя результата для телеметрии и журнала. */
const char *code_result_name(enum code_result result);

/* Обслуживание таймеров набора. Вызывать из главного цикла. */
void code_poll(void);

#endif /* CODE_H */
