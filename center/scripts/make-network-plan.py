wb = Workbook()


def sheet(title, headers, rows, widths, note=None, fills=None, heights=None):
    ws = wb.create_sheet(title)
    r = 1
    if note:
        c = ws.cell(1, 1, note)
        c.font = NOTE
        c.alignment = Alignment(wrap_text=True, vertical="center")
        ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(headers))
        ws.row_dimensions[1].height = 44
        r = 2

    head = r
    for i, h in enumerate(headers, 1):
        c = ws.cell(head, i, h)
        c.font, c.fill, c.border = HDR_FONT, HDR_FILL, BORDER
        c.alignment = Alignment(wrap_text=True, vertical="center")
    ws.row_dimensions[head].height = 30

    for j, row in enumerate(rows):
        for i, v in enumerate(row, 1):
            c = ws.cell(head + 1 + j, i, v)
            c.font = BASE
            c.border = BORDER
            c.alignment = Alignment(wrap_text=True, vertical="top")
            if fills:
                f = fills(row)
                if f:
                    c.fill = f
        if heights:
            ws.row_dimensions[head + 1 + j].height = heights

    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w

    ws.freeze_panes = ws.cell(head + 1, 1)
    ws.auto_filter.ref = f"A{head}:{get_column_letter(len(headers))}{head + len(rows)}"
    return ws


